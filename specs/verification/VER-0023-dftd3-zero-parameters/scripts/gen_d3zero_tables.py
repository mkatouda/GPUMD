#!/usr/bin/env python3
"""Generate the D3(0) tables (r0ab, functional parameters) from dftd3-lib sources.

Usage: gen_d3zero_tables.py <dftd3-lib dir> <output dir>
Reads  <lib>/lib/core.f90  (subroutine setr0ab, subroutine setfuncpar, version.eq.3 block).
Writes r0ab_angstrom.csv, d3zero_params.csv, d3zero_tables.inc, SOURCE.txt into <output dir>.
Nothing is typed by hand; every number is parsed from the source text.
"""
import hashlib
import os
import re
import subprocess
import sys

lib, out = sys.argv[1], sys.argv[2]
src = open(os.path.join(lib, "lib", "core.f90")).read()
NEL = 94
AUTOANG = 0.52917726  # lib/common.f90, checked below

com = open(os.path.join(lib, "lib", "common.f90")).read()
m = re.search(r"autoang\s*=\s*([0-9.]+)d0", com)
assert m and float(m.group(1)) == AUTOANG, "autoang mismatch"

# ---- r0ab: packed lower triangle (k over i>=j); stored in Angstrom, setr0ab divides by autoang
i0 = src.index("subroutine setr0ab(")
i1 = src.index("end subroutine setr0ab")
body = src[i0:i1]
assert "r(i,j)=r0ab(k)/autoang" in body.replace(" ", "")
vals = [None] * (NEL * (NEL + 1) // 2)
nchunk = 0
for mm in re.finditer(r"r0ab\(\s*(\d+):\s*(\d+)\)=\(/(.*?)/\)", body, re.S):
    a, b = int(mm.group(1)), int(mm.group(2))
    nums = re.findall(r"[-+]?\d+\.\d+", mm.group(3).replace("&", " "))
    assert len(nums) == b - a + 1, (a, b, len(nums))
    for k, s in enumerate(nums):
        assert vals[a - 1 + k] is None
        vals[a - 1 + k] = s
    nchunk += 1
assert all(v is not None for v in vals), "missing r0ab entries"
R = [[None] * NEL for _ in range(NEL)]
k = 0
for i in range(NEL):
    for j in range(i + 1):
        R[i][j] = R[j][i] = vals[k]
        k += 1
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "r0ab_angstrom.csv"), "w") as f:
    f.write("# D3(0) pair cutoff radii r0ab in ANGSTROM (as stored in dftd3-lib; the lib divides by autoang=0.52917726 to get bohr)\n")
    f.write("# rows/cols: Z=1..94, symmetric; generated by gen_d3zero_tables.py\n")
    for i in range(NEL):
        f.write(",".join(R[i][j] for j in range(NEL)) + "\n")

# ---- functional parameters: version.eq.3 block of setfuncpar
f0 = src.index("subroutine setfuncpar(")
f1 = src.index("end subroutine setfuncpar")
sf = src[f0:f1]
b0 = sf.index("if (version.eq.3)then")
b1 = sf.index("if (version.eq.2)then")
blk = sf[b0:b1]
assert re.search(r"s6\s*=1\.0d0", blk) and re.search(r"alp\s*=14\.0d0", blk) and re.search(r"rs18\s*=1\.0d0", blk)
j = blk.index("else\n")
parts = {"def2-QZVP": blk[:j], "TZVPP": blk[j:]}
rows = []
for variant, txt in parts.items():
    txt = "\n".join(l.split("!")[0] for l in txt.splitlines())  # strip comments (dftb3 is commented out)
    for mm in re.finditer(r'case\s*\("([^"]+)"\)(.*?)(?=\n\s*case\b|\n\s*end select)', txt, re.S):
        name, bd = mm.group(1), mm.group(2)
        p = {"s6": "1.0", "rs6": None, "s18": None, "rs18": "1.0"}
        for a in re.finditer(r"\b(s6|rs6|s18|rs18)\s*=\s*([-+]?\d+\.?\d*)(?:d0)?", bd):
            p[a.group(1)] = a.group(2)
        assert p["rs6"] is not None and p["s18"] is not None, name
        rows.append((name, variant, p["s6"], p["rs6"], p["s18"], p["rs18"]))
assert not any(r[0] == "dftb3" for r in rows)
assert len({(r[0], r[1]) for r in rows}) == len(rows), "duplicate functional entries"
with open(os.path.join(out, "d3zero_params.csv"), "w") as f:
    f.write("# D3(0) parameters from dftd3-lib setfuncpar(version=3). columns: functional,basis_variant,s6,sr6,s8,sr8,alpha6,alpha8\n")
    f.write("# basis_variant: def2-QZVP = lib default (TZ=false, Grimme et al. 2010 set); TZVPP = lib 'tz' option\n")
    f.write("# sr6 = lib rs6, s8 = lib s18, sr8 = lib rs18; alpha6=14, alpha8=alpha6+2=16 (prg/main.f90, lib/api.f90)\n")
    for r in rows:
        f.write("%s,%s,%s,%s,%s,%s,14,16\n" % r)


def norm(s):
    return s if "." in s else s + ".0"


q = [r for r in rows if r[1] == "def2-QZVP"]
with open(os.path.join(out, "d3zero_tables.inc"), "w") as f:
    f.write("// GENERATED by gen_d3zero_tables.py from dftd3-lib lib/core.f90 -- DO NOT EDIT BY HAND.\n")
    f.write("// r0ab: packed lower triangle, index(i,j) = i*(i+1)/2 + j for 0-based i>=j (Z = i+1), ANGSTROM.\n")
    f.write("// Divide by the Angstrom-per-bohr constant once to get bohr (dftd3-lib uses 0.52917726).\n")
    f.write("static const double D3ZERO_R0AB_ANGSTROM[%d] = {\n" % len(vals))
    for k in range(0, len(vals), 8):
        f.write("  " + ", ".join(vals[k:k + 8]) + ",\n")
    f.write("};\n\n")
    f.write("// D3(0) functional parameters (def2-QZVP variant): name, s6, sr6, s8, sr8 (alpha6=14, alpha8=16)\n")
    f.write("struct D3ZeroParam { const char* name; double s6, sr6, s8, sr8; };\n")
    f.write("static const D3ZeroParam D3ZERO_PARAMS[%d] = {\n" % len(q))
    for r in q:
        f.write('  {"%s", %s, %s, %s, %s},\n' % (r[0], norm(r[2]), norm(r[3]), norm(r[4]), norm(r[5])))
    f.write("};\n")

commit = subprocess.run(["git", "-C", lib, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
sha = hashlib.sha256(open(os.path.join(lib, "lib", "core.f90"), "rb").read()).hexdigest()
with open(os.path.join(out, "SOURCE.txt"), "w") as f:
    f.write("dftd3-lib commit %s\nlib/core.f90 sha256 %s\nautoang %s\nr0ab entries %d (94*95/2), chunks %d\n"
            "functionals def2-QZVP %d, TZVPP %d\n" % (commit, sha, AUTOANG, len(vals), nchunk, len(q), len(rows) - len(q)))
print(open(os.path.join(out, "SOURCE.txt")).read())
