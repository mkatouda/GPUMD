#!/usr/bin/env python3
"""Generate src/force/dftd2qe_table.cuh from the Quantum ESPRESSO DFT-D3 sources.

Usage: generate_dftd2qe_table.py <QE dft-d3 source dir> <output .cuh>

Provenance of the data (nothing is typed by hand):
  Quantum ESPRESSO tag qe-7.2, commit b4c5e8deeb7d1863e7553a87b45f8d22c21926a5
  dft-d3/pars.f90  : C6 reference table (5 numbers per line: C6 [Hartree bohr^6], Zi + 100*(iref_i - 1),
                     Zj + 100*(iref_j - 1), CN_i, CN_j)
  dft-d3/core.f90  : subroutine setr0ab, the r0ab table in Angstrom
The directory given on the command line holds copies of the two files, e.g.
  git show qe-7.2:dft-d3/pars.f90 > pars.f90 ; git show qe-7.2:dft-d3/core.f90 > core.f90

Definition (QE 7.2, dftd3_version = 2): for a pair of elements, C6_ij is the C6 of the FIRST
reference point of both atoms (QE c6ab(Zi, Zj, 1, 1, 1)), not sqrt(C6_i C6_j); the damping radius is
R0_ij = 1.1 * r0ab(Zi, Zj). Only Z <= 86 is written.

Output: two double arrays of 3741 entries, packed lower triangle, index zl*(zl+1)/2 + zs with
0-based atomic numbers zs <= zl (same packing as the DFT-D3 tables).
The numbers are written with repr(), which round-trips doubles.
"""
import os
import re
import sys

MAX_Z = 86
NPARS = 161925  # 32385 lines x 5 numbers
NR0AB = 4465    # 94 * 95 / 2


def strip_comments(txt):
    return "\n".join(ln[: ln.find("!")] if "!" in ln else ln for ln in txt.splitlines())


def blocks(txt, name):
    """yield (first, last, [tokens]) for every `name(first:last) = (/ ... /)` block"""
    txt = strip_comments(txt).replace("&", " ")
    pat = re.compile(name + r"\(\s*(\d+)\s*:\s*(\d+)\s*\)\s*=\s*\(/(.*?)/\)", re.S)
    for m in pat.finditer(txt):
        toks = [t.strip() for t in m.group(3).replace("\n", " ").split(",") if t.strip()]
        yield int(m.group(1)), int(m.group(2)), toks


def to_float(tok):
    return float(tok.replace("_wp", "").replace("D", "e").replace("d", "e"))


def collect(txt, name, count):
    vals = [None] * count
    for a, b, toks in blocks(txt, name):
        assert len(toks) == b - a + 1, (name, a, b, len(toks))
        for k, t in enumerate(toks):
            assert vals[a - 1 + k] is None, (name, a + k)
            vals[a - 1 + k] = to_float(t)
    assert all(v is not None for v in vals), name
    return vals


def limit(iat, jat):
    """QE limit(): atomic number and reference index of both atoms"""
    iadr = jadr = 1
    while iat > 100:
        iat -= 100
        iadr += 1
    while jat > 100:
        jat -= 100
        jadr += 1
    return iat, jat, iadr, jadr


def main():
    src, out = sys.argv[1], sys.argv[2]
    pars = collect(open(os.path.join(src, "pars.f90"), encoding="latin-1").read(), "pars", NPARS)
    core = open(os.path.join(src, "core.f90"), encoding="latin-1").read()
    core = core[core.index("subroutine setr0ab"): core.index("end subroutine setr0ab")]
    r0ab = collect(core, "r0ab", NR0AB)  # setr0ab fills the lower triangle row by row

    npair = MAX_Z * (MAX_Z + 1) // 2
    c6 = [None] * npair
    for nn in range(len(pars) // 5):
        kk = 5 * nn
        zi, zj, ia, ja = limit(int(pars[kk + 1]), int(pars[kk + 2]))
        if ia == 1 and ja == 1 and zi <= MAX_Z and zj <= MAX_Z:
            zs, zl = sorted((zi - 1, zj - 1))
            idx = zl * (zl + 1) // 2 + zs
            assert c6[idx] is None, (zi, zj)
            c6[idx] = pars[kk]
    assert all(v is not None for v in c6)
    r0 = r0ab[:npair]  # entries (i, j), j <= i, packed the same way

    def emit(f, name, comment, values):
        f.write(f"// {comment}\n")
        f.write(f"static const double {name}[{len(values)}] = {{\n")
        for k in range(0, len(values), 4):
            f.write("  " + ", ".join(repr(v) for v in values[k: k + 4]) + ",\n")
        f.write("};\n\n")

    with open(out, "w") as f:
        f.write(
            "/*\n"
            "    This file is part of GPUMD (see the license in dftd2.cu).\n"
            "    GENERATED by tools/dftd2_qe_table/generate_dftd2qe_table.py: do not edit by hand.\n"
            "    Source: Quantum ESPRESSO tag qe-7.2 (commit b4c5e8deeb7d1863e7553a87b45f8d22c21926a5),\n"
            "    dft-d3/pars.f90 (C6) and dft-d3/core.f90 (setr0ab, r0ab).\n"
            "*/\n\n#pragma once\n\n"
            f"#define DFTD2QE_MAX_Z {MAX_Z}\n"
            f"#define DFTD2QE_NUM_PAIRS {npair}\n\n"
            "// Packed lower triangle, index zl * (zl + 1) / 2 + zs with 0-based atomic numbers zs <= zl.\n\n"
        )
        emit(f, "DFTD2QE_C6_EH_BOHR6",
             "C6 of the first reference point of both atoms (QE c6ab(Zi, Zj, 1, 1, 1)), Hartree bohr^6",
             c6)
        emit(f, "DFTD2QE_R0AB_A", "r0ab (QE setr0ab), Angstrom", r0)


if __name__ == "__main__":
    main()
