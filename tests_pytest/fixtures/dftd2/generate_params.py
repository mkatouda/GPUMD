"""Generate dftd2_params.csv (DFT-D2 C6/R0, Z = 1..86) mechanically from the dftd3-lib source.

Source: dftd3-lib, `prg/extras.f90`, `subroutine loadoldpar` (arrays r0(1:86), c6(1:86)); commit
3c99ee981266548a37588abe3a6f5cb56092d51a ("DFTD3 (deprecated)", repackaging of Grimme's DFTD3
V3.1 Rev 1; GPL v1 or later). Original publication: S. Grimme, J. Comput. Chem. 27, 1787 (2006).
Nothing is typed by hand: the numbers are parsed from the Fortran text. Run

    python generate_params.py /path/to/dftd3-lib/prg/extras.f90 [dftd3-lib commit]

and the CSV is rewritten next to this script. Do not edit the CSV by hand.

Units and conversions (constants as in dftd3-lib `lib/common.f90` / `prg`):
  c6_J_nm6_mol : as stored in the source, J nm^6 mol^-1
  r0_A         : as stored in the source, Angstrom (the published R0 is 1.1 * r0, `rs6 = 1.1`)
  R0_pub_A     : 1.1 * r0_A
  c6_Eh_bohr6  : c6 * c6conv, c6conv = 1e-3 / 2625.4999 / (0.52917726 / 10)**6
  c6_eV_A6     : c6_Eh_bohr6 * 27.21138505 * 0.52917726**6
"""
import hashlib
import re
import sys
from pathlib import Path

from ase.data import chemical_symbols

BOHR = 0.52917726          # Angstrom, dftd3-lib autoang
KJMOL_PER_EH = 2625.4999   # dftd3-lib c6conv
EV_PER_EH = 27.21138505    # value requested for this project
C6CONV = 1e-3 / KJMOL_PER_EH / (BOHR / 10) ** 6     # J nm^6 mol^-1 -> Eh bohr^6
C6_TO_EV_A6 = C6CONV * EV_PER_EH * BOHR ** 6


def extract_loadoldpar(text):
    start = text.index('subroutine loadoldpar')
    end = text.index('end subroutine loadoldpar')
    return text[start:end]


def parse_array(block, name):
    m = re.search(name + r'\(1:86\)\s*=\s*\(/(.*?)/\)', block, re.S)
    body = re.sub(r'!.*', '', m.group(1))            # drop Fortran comments
    body = body.replace('&', ' ')
    values = [float(tok.lower().replace('d', 'e')) for tok in body.split(',') if tok.strip()]
    if len(values) != 86:
        raise ValueError(f'{name}: expected 86 values, got {len(values)}')
    return values


def main(source, commit='unknown', out=None):
    text = Path(source).read_text()
    block = extract_loadoldpar(text)
    r0 = parse_array(block, 'r0')
    c6 = parse_array(block, 'c6')
    digest = hashlib.sha256(block.encode()).hexdigest()
    out = Path(out) if out else Path(__file__).with_name('dftd2_params.csv')
    with open(out, 'w') as fh:
        fh.write('# DFT-D2 parameters, generated by generate_params.py (do not edit by hand)\n')
        fh.write('# source: dftd3-lib prg/extras.f90 subroutine loadoldpar, commit %s\n' % commit)
        fh.write('# sha256(loadoldpar text up to "end subroutine"): %s\n' % digest)
        fh.write('# primary reference: S. Grimme, J. Comput. Chem. 27, 1787 (2006); published R0 = 1.1*r0\n')
        fh.write('# constants: bohr=%s A; 1 Eh=%s kJ/mol; 1 Eh=%s eV\n'
                 % (BOHR, KJMOL_PER_EH, EV_PER_EH))
        fh.write('Z,symbol,c6_J_nm6_mol,r0_A,R0_pub_A,c6_Eh_bohr6,c6_eV_A6\n')
        for z in range(1, 87):
            c, r = c6[z - 1], r0[z - 1]
            fh.write('%d,%s,%r,%r,%.10g,%.17e,%.17e\n'
                     % (z, chemical_symbols[z], c, r, 1.1 * r, c * C6CONV, c * C6_TO_EV_A6))
    print('wrote', out, 'sha256', digest)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else 'unknown')
